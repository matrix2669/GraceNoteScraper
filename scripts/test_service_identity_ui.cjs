const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '../lineuparr.html'), 'utf8');
for (const match of html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(match[1]);
const start = html.indexOf('    function activeDuplicateGroups()');
const end = html.indexOf('    function renderSources()', start);
assert(start > 0 && end > start);
const context = vm.createContext({ draft: {channels:[{id:'sd',included:true},{id:'hd',included:true},{id:'repeat',included:false}],duplicateGroups:[{channelIds:['sd','hd','repeat'],keepId:'hd'}]}});
vm.runInContext(html.slice(start,end), context);
let group = vm.runInContext('activeDuplicateGroups()[0]', context);
assert.deepEqual(Array.from(group.channels,c=>c.id), ['sd','hd']);
context.group = group;
assert.deepEqual(Array.from(vm.runInContext('duplicateInitialKeeps(group)', context)), ['hd']);
group.channels[0].inclusionChoice=true;
assert.deepEqual(Array.from(vm.runInContext('duplicateInitialKeeps(group)', context)), ['sd']);
group.channels[1].inclusionChoice=true;
assert.deepEqual(Array.from(vm.runInContext('duplicateInitialKeeps(group)', context)), ['sd','hd']);
assert.match(html,/input.checked = initialKeeps.has\(channel.id\)/);
assert.equal(context.draft.channels[2].included,false);
console.log('Service identity UI: complete component, excluded repeat, single default and saved multiple keepers passed');
